const fs = require('fs');
const path = require('path');
const PDFDocument = require('pdfkit');

const FONT = 'C:/Windows/Fonts/simhei.ttf';
const outDir = path.join(__dirname, '..', 'src', 'mock', 'pdfs');
fs.mkdirSync(outDir, { recursive: true });

function buildDoc(filename, pages) {
  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ size: 'A4', margins: { top: 50, bottom: 50, left: 50, right: 50 } });
    const stream = fs.createWriteStream(path.join(outDir, filename));
    doc.pipe(stream);
    doc.registerFont('zh', FONT);
    doc.font('zh');

    pages.forEach((page, i) => {
      if (i > 0) doc.addPage();
      doc.fontSize(16).text(page.title, { align: 'center' });
      doc.moveDown(0.6);
      doc.fontSize(11);
      for (const line of page.lines) {
        doc.text(line, { lineGap: 5 });
      }
    });

    doc.end();
    stream.on('finish', resolve);
    stream.on('error', reject);
  });
}

